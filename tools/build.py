#!/usr/bin/env python3
"""
build.py — 記事・ギャラリーの静的ページと sitemap.xml を自動生成する（SEO用）

  使い方（サイトのフォルダで）:   python tools/build.py
  Windows なら tools/build.bat をダブルクリックでもOK。

やること
  1. data/news.json・data/gallery.json の書き間違いをチェック（IDの重複、親記事が無い、日付の形式など）
  2. 記事ごとに news/<id>.html、ギャラリーごとに gallery/<id>.html を作成
     （<title>・<meta description>・OGP・canonical・構造化データ入り。中身の表示は通常のページと同じ）
  3. sitemap.xml を作り直す（固定ページ＋全記事＋全ギャラリー）
  4. data/_generated.json に作成したページの一覧を書く（サイト側で正規URLの判定に使用）

※ 生成したファイルは手で編集しないでください（次回の実行で上書きされます）。
※ 記事を削除した場合、そのページも次回の実行で自動的に削除されます。
※ Python 3.8 以上・追加インストール不要。
"""
import html
import json
import re
import sys
from datetime import date
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
MARK = '<!-- generated by tools/build.py: 手で編集しないでください -->'
SITE_NAME = '上智大学自動車部'
# sitemap に載せない固定ページ
EXCLUDE_PAGES = {'how-to-update.html', 'news-detail.html', 'gallery-detail.html'}
ID_RE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_-]*$')
DATE_RE = re.compile(r'^\d{4}-\d{2}-\d{2}$')

try:
    sys.stdout.reconfigure(encoding='utf-8')
except Exception:
    pass

errors, warnings = [], []


def load_json(rel, default=None):
    path = ROOT / rel
    if not path.exists():
        if default is not None:
            return default
        errors.append(f'{rel} が見つかりません')
        return []
    try:
        return json.loads(path.read_text(encoding='utf-8-sig'))
    except json.JSONDecodeError as e:
        errors.append(f'{rel} の {e.lineno} 行目 {e.colno} 文字目付近に書き間違いがあります（{e.msg}）。カンマ・引用符・カッコを確認してください。')
        return default if default is not None else []


def to_text(c):
    return '\n\n'.join(c) if isinstance(c, list) else str(c or '')


def plain(c):
    s = to_text(c)
    s = re.sub(r'!\[[^\]]*\]\([^)]*\)', '', s)
    s = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', s)
    s = re.sub(r'(?m)^\s*(#{2,4}|>|-|\*|\d+\.)\s+', '', s)
    s = s.replace('**', '').replace('__', '')
    return re.sub(r'\s+', ' ', s).strip()


def cut(s, n):
    return s[:n].rstrip() + '…' if len(s) > n else s


def esc(s):
    return html.escape(str(s or ''), quote=True)


def check_file(rel, where):
    if rel and not re.match(r'^https?://', rel) and not (ROOT / rel).exists():
        warnings.append(f'{where}: 画像 {rel} が見つかりません（代替画像が表示されます）')


# ---------------------------------------------------------------- データ読み込み・チェック
site = load_json('data/site.json', {})
base = str(site.get('baseUrl') or 'https://YOUR-DOMAIN').rstrip('/')
posts = [p for p in load_json('data/news.json') if isinstance(p, dict) and not p.get('draft')]
galleries = [g for g in load_json('data/gallery.json') if isinstance(g, dict) and not g.get('draft')]
if errors:
    print('\n'.join('✖ ' + e for e in errors))
    sys.exit(1)


def check_ids(items, label):
    seen = set()
    for i, it in enumerate(items, 1):
        pid = it.get('id')
        where = f'{label} {i}件目「{it.get("title", "")}」'
        if not pid:
            errors.append(f'{where}: "id" がありません')
            continue
        if not ID_RE.match(str(pid)):
            errors.append(f'{where}: id "{pid}" に使えない文字があります（半角英数字・-・_ のみ）')
        if pid in seen:
            errors.append(f'{where}: id "{pid}" が重複しています')
        seen.add(pid)
        if not it.get('title'):
            errors.append(f'{where}: "title" がありません')
        d = it.get('date')
        if d and not DATE_RE.match(str(d)):
            errors.append(f'{where}: date "{d}" は YYYY-MM-DD の形式で書いてください（例 2026-11-20）')


check_ids(posts, 'news.json')
check_ids(galleries, 'gallery.json')
post_by_id = {p['id']: p for p in posts if p.get('id')}
gal_by_id = {g['id']: g for g in galleries if g.get('id')}

for p in posts:
    pid = p.get('id')
    if p.get('parentId'):
        if p['parentId'] not in post_by_id:
            errors.append(f'news.json「{p.get("title")}」: 親記事 parentId "{p["parentId"]}" が見つかりません')
        elif p['parentId'] == pid:
            errors.append(f'news.json「{p.get("title")}」: 自分自身を親記事にしています')
    if p.get('galleryId') and p['galleryId'] not in gal_by_id:
        warnings.append(f'news.json「{p.get("title")}」: galleryId "{p["galleryId"]}" のギャラリーがありません')
    if not p.get('date') and not any(c.get('parentId') == pid for c in posts):
        warnings.append(f'news.json「{p.get("title")}」: date がありません')
    check_file(p.get('thumbnail'), f'news.json「{p.get("title")}」')
    for im in p.get('images') or []:
        check_file(im if isinstance(im, str) else (im or {}).get('src'), f'news.json「{p.get("title")}」')

def gallery_photos(g):
    photos = [x if isinstance(x, str) else (x or {}).get('src') for x in g.get('photos') or []]
    photos = [x for x in photos if x]
    f = g.get('photoFolder') or {}
    if f.get('path') and int(f.get('count') or 0) > 0:
        start, pad, ext = int(f.get('start') or 1), int(f.get('pad') or 0), str(f.get('ext') or 'jpg').lstrip('.')
        for n in range(start, start + int(f['count'])):
            photos.append(f'{str(f["path"]).rstrip("/")}/{f.get("prefix", "")}{str(n).zfill(pad)}.{ext}')
    return photos


for g in galleries:
    for src in ([g.get('cover')] if g.get('cover') else []) + gallery_photos(g):
        check_file(src, f'gallery.json「{g.get("title")}」')
    if g.get('articleId') and g['articleId'] not in post_by_id:
        warnings.append(f'gallery.json「{g.get("title")}」: articleId "{g["articleId"]}" の記事がありません')

if errors:
    print('✖ エラーがあるため中止しました。直してからもう一度実行してください。')
    print('\n'.join('  ✖ ' + e for e in errors))
    sys.exit(1)


# ---------------------------------------------------------------- 記事の補完（blog.js と同じルール）
def ancestors(p):
    chain, seen, a = [], {p['id']}, post_by_id.get(p.get('parentId'))
    while a and a['id'] not in seen:
        chain.insert(0, a)
        seen.add(a['id'])
        a = post_by_id.get(a.get('parentId'))
    return chain


def first_src(lst):
    for im in lst or []:
        src = im if isinstance(im, str) else (im or {}).get('src')
        if src:
            return src
    return ''


for p in posts:
    chain = ancestors(p)
    p['_chain'] = chain
    p['_category'] = p.get('category') or next((a.get('category') for a in reversed(chain) if a.get('category')), None) or 'お知らせ'
    p['_thumb'] = p.get('thumbnail') or first_src(p.get('images')) or next((a.get('thumbnail') for a in reversed(chain) if a.get('thumbnail')), '')
for p in posts:
    if not p.get('date'):
        kids = sorted((c.get('date') or '' for c in posts if c.get('parentId') == p['id']), reverse=True)
        p['_date'] = kids[0] if kids else ''
    else:
        p['_date'] = p['date']
    text = plain(p.get('content'))
    p['_text'] = text
    p['_desc'] = p.get('description') or cut(text, 120) or f'{p["title"]}｜{SITE_NAME}'


# ---------------------------------------------------------------- HTML生成
def abs_url(u):
    if not u:
        return ''
    return u if re.match(r'^https?://', u) else f'{base}/{u.lstrip("/")}'


def make_page(template, *, out_rel, page_id, title, desc, image, ld, hero_html, main_id, main_html):
    s = template
    full = f'{title} | {SITE_NAME}'
    canonical = abs_url(out_rel)
    s = s.replace('<meta charset="UTF-8">', '<meta charset="UTF-8">\n' + MARK + '\n<base href="../">', 1)
    s = re.sub(r'<title>.*?</title>', f'<title>{esc(full)}</title>', s, count=1, flags=re.S)
    s = re.sub(r'(<meta name="description" content=")[^"]*(")', lambda m: m.group(1) + esc(desc) + m.group(2), s, count=1)
    for key in ('og:title', 'twitter:title'):
        s = re.sub(rf'(<meta (?:property|name)="{key}" content=")[^"]*(")', lambda m: m.group(1) + esc(full) + m.group(2), s, count=1)
    for key in ('og:description', 'twitter:description'):
        s = re.sub(rf'(<meta (?:property|name)="{key}" content=")[^"]*(")', lambda m: m.group(1) + esc(desc) + m.group(2), s, count=1)
    if image:
        for key in ('og:image', 'twitter:image'):
            s = re.sub(rf'(<meta (?:property|name)="{key}" content=")[^"]*(")', lambda m: m.group(1) + esc(abs_url(image)) + m.group(2), s, count=1)
    s = re.sub(r'(<meta property="og:url" content=")[^"]*(")', lambda m: m.group(1) + esc(canonical) + m.group(2), s, count=1)
    s = re.sub(r'(<link rel="canonical" href=")[^"]*(")', lambda m: m.group(1) + esc(canonical) + m.group(2), s, count=1)
    s = s.replace('<meta property="og:type" content="website">', '<meta property="og:type" content="article">', 1)
    lds = ''.join(f'<script type="application/ld+json" data-blog-ld>{json.dumps(x, ensure_ascii=False)}</script>\n' for x in ld)
    s = s.replace('</head>', lds + '</head>', 1)
    s = re.sub(r'<body([^>]*)>', lambda m: f'<body{m.group(1)} data-id="{esc(page_id)}">', s, count=1)
    # <base> があるので、ページ内リンク（#main-content）は自分のURLを明示する
    s = s.replace('href="#main-content"', f'href="{esc(out_rel)}#main-content"')
    # 検索エンジン向けに中身をあらかじめ入れておく（表示時は JavaScript が同じ場所を描き直す）
    s = re.sub(r'(<div class="container" id="(?:post|gallery)-hero">).*?(</div></section>)', lambda m: m.group(1) + hero_html + m.group(2), s, count=1, flags=re.S)
    s = re.sub(rf'(<div [^>]*id="{main_id}"[^>]*>)<p class="notice">読み込み中…</p>(</div>)', lambda m: m.group(1) + main_html + m.group(2), s, count=1)
    return s


def crumbs_ld(items):
    return {'@context': 'https://schema.org', '@type': 'BreadcrumbList', 'itemListElement': [
        {'@type': 'ListItem', 'position': i + 1, 'name': n, **({'item': abs_url(u)} if u else {})} for i, (n, u) in enumerate(items)]}


def write_pages(kind, items, template_rel, render):
    out_dir = ROOT / kind
    out_dir.mkdir(exist_ok=True)
    template = (ROOT / template_rel).read_text(encoding='utf-8')
    made = []
    for it in items:
        rel = f'{kind}/{it["id"]}.html'
        (ROOT / rel).write_text(make_page(template, out_rel=rel, page_id=it['id'], **render(it)), encoding='utf-8', newline='\n')
        made.append(it['id'])
    # 記事を削除したときは、古い生成ページも削除（このスクリプトが作ったファイルだけ）
    removed = 0
    for f in out_dir.glob('*.html'):
        if f.stem not in made and MARK in f.read_text(encoding='utf-8', errors='ignore')[:600]:
            f.unlink()
            removed += 1
    return made, removed


def render_post(p):
    items = [('Home', 'index.html'), ('News', 'news.html'), (p['_category'], f'news.html?category={quote(p["_category"])}')]
    items += [(a['title'], f'news/{a["id"]}.html') for a in p['_chain']] + [(p['title'], None)]
    paras = ''.join(f'<p>{esc(x)}</p>' for x in re.split(r'\n\s*\n', to_text(p.get('content'))) if plain(x))
    kids = [c for c in posts if c.get('parentId') == p['id']]
    kids_li = ''.join('<li><a href="news/%s.html">%s</a></li>' % (esc(c['id']), esc(c['title'])) for c in kids)
    kids_html = '<h2 class="post-section-title">子記事一覧</h2><ul>%s</ul>' % kids_li if kids else ''
    parent = p['_chain'][-1] if p['_chain'] else None
    title = p['title'] + (f' | {parent["title"]}' if parent else '') + ' | News'
    article = {'@context': 'https://schema.org', '@type': 'BlogPosting', 'headline': p['title'], 'datePublished': p['_date'],
               'description': p['_desc'], 'keywords': ','.join(p.get('tags') or []), 'articleSection': p['_category'],
               'author': {'@type': 'Organization', 'name': SITE_NAME}, 'publisher': {'@type': 'Organization', 'name': SITE_NAME},
               'mainEntityOfPage': abs_url(f'news/{p["id"]}.html')}
    if p.get('updated'):
        article['dateModified'] = p['updated']
    if p['_thumb']:
        article['image'] = abs_url(p['_thumb'])
    return dict(title=title, desc=p['_desc'], image=p['_thumb'], ld=[crumbs_ld(items), article],
                hero_html=f'<p class="eyebrow eyebrow-light">{esc(p["_category"])}</p><h1>{esc(p["title"])}</h1><p><time datetime="{esc(p["_date"])}">{esc(p["_date"].replace("-", "/"))}</time></p>',
                main_id='post-main', main_html=f'<article class="post-article"><div class="post-content">{paras}</div>{kids_html}</article>')


def render_gallery(g):
    photos = gallery_photos(g)
    items = [('Home', 'index.html'), ('Gallery', 'album.html'), (g['title'], None)]
    desc = g.get('description') or f'{g["title"]}の写真{len(photos)}枚。{SITE_NAME}のギャラリー。'
    return dict(title=f'{g["title"]}（写真{len(photos)}枚） | Gallery', desc=desc, image=g.get('cover') or (photos[0] if photos else ''),
                ld=[crumbs_ld(items), {'@context': 'https://schema.org', '@type': 'ImageGallery', 'name': g['title'],
                                       'datePublished': g.get('date', ''), 'description': desc}],
                hero_html=f'<p class="eyebrow eyebrow-light">Gallery</p><h1>{esc(g["title"])}</h1><p>{esc(desc)}</p>',
                main_id='gallery-main', main_html=f'<p>{len(photos)}枚の写真</p>')


news_made, news_removed = write_pages('news', posts, 'news-detail.html', render_post)
gal_made, gal_removed = write_pages('gallery', galleries, 'gallery-detail.html', render_gallery)

(ROOT / 'data' / '_generated.json').write_text(json.dumps(
    {'note': 'tools/build.py が自動作成。手で編集しないでください。', 'builtAt': date.today().isoformat(),
     'news': news_made, 'gallery': gal_made}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')

# ---------------------------------------------------------------- sitemap.xml
urls = [(f'{base}/', None)]
for f in sorted(ROOT.glob('*.html')):
    if f.name not in EXCLUDE_PAGES and f.name != 'index.html':
        urls.append((f'{base}/{f.name}', None))
for p in posts:
    urls.append((abs_url(f'news/{p["id"]}.html'), p.get('updated') or p['_date'] or None))
for g in galleries:
    urls.append((abs_url(f'gallery/{g["id"]}.html'), g.get('date') or None))
xml = ['<?xml version="1.0" encoding="UTF-8"?>', '<!-- tools/build.py が自動作成。記事・ギャラリーを追加したら build.py を再実行してください。 -->',
       '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
for loc, lastmod in urls:
    xml.append(f'  <url><loc>{esc(loc)}</loc>' + (f'<lastmod>{esc(lastmod)}</lastmod>' if lastmod and DATE_RE.match(lastmod) else '') + '</url>')
xml.append('</urlset>')
(ROOT / 'sitemap.xml').write_text('\n'.join(xml) + '\n', encoding='utf-8', newline='\n')

# ---------------------------------------------------------------- 結果
print('✔ 完了しました')
print(f'  記事ページ      news/     {len(news_made)}件' + (f'（古いページ {news_removed}件を削除）' if news_removed else ''))
print(f'  ギャラリー      gallery/  {len(gal_made)}件' + (f'（古いページ {gal_removed}件を削除）' if gal_removed else ''))
print(f'  sitemap.xml     {len(urls)}件のURL')
if 'YOUR-DOMAIN' in base:
    print('  ※ data/site.json の baseUrl が仮のURL（YOUR-DOMAIN）のままです。公開URLに変えてから再実行してください。')
if warnings:
    print(f'\n⚠ 確認してください（{len(warnings)}件。公開はできます）')
    print('\n'.join('  ⚠ ' + w for w in warnings[:40]))
    if len(warnings) > 40:
        print(f'  …ほか {len(warnings) - 40}件')
print('\n次に：news/・gallery/ フォルダ、sitemap.xml、data/_generated.json もサーバーにアップロードしてください。')
